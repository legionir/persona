        lines.append("")
        lines.append("**Actions:**")
        for j, a in enumerate(actions, 1):
            lines.append(f"{j}. {a}")
        lines.append("")
        lines.append("**Validation:**")
        lines.append(f"- {p['quality']}")
        lines.append("- ورودی‌ها موجود و معتبر باشند؛ هیچ تعارض/ناسازگاری نامحلولی باقی نمانده باشد.")
