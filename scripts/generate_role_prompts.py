def load_details() -> dict[str, dict]:
    """Return title -> persona dict from details.md (after header + separator)."""
    result: dict[str, dict] = {}
    lines = DETAILS.read_text(encoding="utf-8").splitlines()
    # line 0 = header, line 1 = separator, data starts line 2
    for ln in lines[2:]:
        s = ln.strip()
        if not s.startswith("|"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if cells and cells[0] == "":
            cells = cells[1:]
        if cells and cells[-1] == "":
            cells = cells[:-1]
        if len(cells) != DETAIL_COLS:
            continue
        title = cells[0]
        data = {
            "duties": cells[1],
            "mission": cells[3],
            "responsibilities": cells[4],
            "scope": cells[5],
            "required": cells[6],
            "optional": cells[7],
            "context": cells[8],
            "preconditions": cells[9],
            "procedure": cells[10],
            "decision": cells[11],
            "allowed": cells[12],
            "restricted": cells[13],
            "outputs": cells[14],
            "quality": cells[15],
            "evidence": cells[16],
            "handoff": cells[17],
            "escalation": cells[18],
            "permissions": cells[19],
            "lifecycle": cells[20],
            "memory": cells[21],
            "kpi": cells[22],
        }
        result[title] = data
    return result


