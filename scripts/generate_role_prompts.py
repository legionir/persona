def _slug(title: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", title)
    if not words:
        return re.sub(r"\s+", "-", title).strip("-").lower()
    s = "-".join(w.lower() for w in words)
    return re.sub(r"-+", "-", s).strip("-")


def _lines(items) -> str:
    return "\n".join(f"- {x}" for x in items)


